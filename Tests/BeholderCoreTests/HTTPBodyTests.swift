private let expectedBody = "{\"appid\":4427310,\"name\":\"Example App\",\"depots\":[1,2,3],\"note\":\"padding to make gzip worthwhile \"}                                        "

@Suite("Reading an HTTP body")
struct HTTPBodyTests {

    /// The case that started this: a body that is compressed, not encrypted, and so reads
    /// as noise until something undoes the encoding.
    @Test("A gzip-encoded body is decompressed and shown as text")
    func gzipBody() throws {
        let message = try #require(HTTPPreview.parse(gzipResponse))
        let body = try #require(message.body)

        #expect(body.text == expectedBody)
        #expect(body.note.contains("gzip undone"))
        #expect(!body.note.contains("cut short"), "this stream ended properly")
    }

    @Test("A body cut short by the excerpt yields its prefix, and says so")
    func truncatedBody() throws {
        let message = try #require(HTTPPreview.parse(gzipResponseCutShort))
        let body = try #require(message.body)

        let text = try #require(body.text)
        #expect(!text.isEmpty)
        #expect(expectedBody.hasPrefix(text), "a prefix of the real body, never a guess")
        #expect(body.note.contains("cut short by the excerpt"))
    }

    @Test("Chunked framing comes off before the encoding under it")
    func chunkedBody() throws {
        let message = try #require(HTTPPreview.parse(chunkedGzipResponse))
        let body = try #require(message.body)

        #expect(body.text == expectedBody)
        #expect(body.note.contains("de-chunked"))
        #expect(body.note.contains("gzip undone"))
    }

    /// Decoding is not the same as being readable. A PNG survives every decoder it is
    /// offered to and is still not text, so it is named rather than rendered — the hex dump
    /// below it in the reader is the honest view of those bytes.
    @Test("A body that is not text is reported as such rather than rendered")
    func binaryBody() throws {
        let body = try #require(HTTPPreview.parse(pngResponse)?.body)
        #expect(body.text == nil)
        #expect(body.note.contains("not text"))
    }

    /// The same rule the protocol sniffer follows: what was not read is reported as not
    /// read, never guessed at.
    @Test("An encoding with no decoder is named, not attempted")
    func undecodableEncoding() throws {
        let body = try #require(HTTPPreview.parse(brotliResponse)?.body)
        #expect(body.text == nil)
        #expect(body.note.contains("br"))
    }

    @Test("A request with no body has none, rather than an empty one")
    func noBody() throws {
        let message = try #require(HTTPPreview.parse(requestWithNoBody))
        #expect(message.isComplete)
        #expect(message.body == nil)
        #expect(message.headers.contains(HTTPPreview.Header(
            name: "Host", value: "clientconfig.akamai.steamstatic.com")))
    }

    /// The headers still have to survive all of this: the boundary moved from the decoded
    /// text into the byte array, and a CRLF is one Swift `Character` but two bytes.
    @Test("Headers are unaffected by the move to a byte-level body split")
    func headersStillParse() throws {
        let message = try #require(HTTPPreview.parse(gzipResponse))
        #expect(message.startLine == "HTTP/1.1 200 OK")
        #expect(message.headers.count == 2)
        #expect(message.isComplete)
    }
}

@Suite("Choosing which reading applies to an excerpt")
struct PayloadPreviewTests {

    /// This rule used to live in a SwiftUI `body`, where nothing could reach it.
    @Test("HTTP wins over DNS, and neither is claimed for bytes that are neither")
    func precedence() {
        #expect(PayloadPreview.of(gzipResponse) == .http(HTTPPreview.parse(gzipResponse)!))

        var query: [UInt8] = [0x12, 0x34, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]
        query += [7] + Array("example".utf8) + [3] + Array("com".utf8) + [0]
        query += [0x00, 0x01, 0x00, 0x01]
        guard case .dns(let messages) = PayloadPreview.of(query) else {
            Issue.record("a DNS query should be read as DNS")
            return
        }
        #expect(messages.count == 1)

        // A WireGuard keepalive: recognised by the sniffer, readable by neither parser.
        #expect(PayloadPreview.of([4, 0, 0, 0] + (4..<32).map { UInt8($0) }) == .unrecognised)
        #expect(PayloadPreview.of([]) == .unrecognised)
    }
}
